def catalog() -> dict:
    products = []
    for group, (category_id, (label, models)) in enumerate(CATEGORIES.items(), start=1):
        for index, model in enumerate(models, start=1):
            pid = f"OD-{group}{index:03d}"
            weight = f"{model.weight} g"
            specs = {"重量": weight, "材质": model.material, **model.specs}
            detail = "；".join(f"{key}：{value}" for key, value in model.specs.items())
            attributes = {
                "category_label": label,
                "weight_g": str(model.weight),
                "material": model.material,
                "activity": model.use,
                "highlight_1": weight,
                "highlight_2": next(iter(model.specs.values())),
                "color": model.specs.get("颜色", "森林绿 / 岩灰配色"),
            }
            for key, name in (
                ("容量", "capacity"),
                ("人数", "capacity_people"),
                ("舒适温度", "comfort_temperature"),
                ("R 值", "r_value"),
            ):
                if key in specs:
                    attributes[name] = specs[key]
            for key, name in (
                ("容量", "capacity_l"),
                ("人数", "people"),
                ("舒适温度", "comfort_temperature_c"),
                ("R 值", "r_value"),
                ("外帐防水", "waterproof_mm"),
                ("防水参数", "waterproof_mm"),
            ):
                raw = specs.get(key, "")
                number = re.match(r"-?\d+(?:\.\d+)?", raw)
                if number:
                    value = float(number.group())
                    if name == "capacity_l" and "ml" in raw.lower():
                        value /= 1000
                    attributes[name] = f"{value:g}"
            product = {
                "product_id": pid,
                "title": model.title,
                "brand": None,
                "price": model.price,
                "currency": "CNY",
                "category": category_id,
                "rating": round(4.1 + ((group * 3 + index) % 8) / 10, 1),
                "review_count": 35 + (group * 41 + index * 29) % 390,
                "in_stock": not (group in (1, 3, 6) and index == 12),
                "labels": ["轻量之选" if model.weight < 500 else "户外装备"],
                "attributes": attributes,
                "search_terms": [
                    label,
                    model.title,
                    model.use,
                    *model.specs.keys(),
                    *model.specs.values(),
                ],
                "short_description": model.use + "。",
                "long_description": f"{model.use}。\n{detail}。\n选购限制：{model.limitation}。\n维护：使用后清洁并彻底晾干，遵循随附说明。商品及参数为虚构体验数据。",
                "specs": specs | {"适合场景": model.use, "选购限制": model.limitation},
                "review_highlights": [
                    f"模拟体验：{next(iter(model.specs))}与页面说明一致，适合{model.use}。",
                    f"模拟提醒：{model.limitation}。",
                ],
            }
            sizes: tuple[str, ...] = ()
            if category_id == "outdoor-apparel":
                sizes = ("S", "M", "L", "XL")
            elif category_id == "outdoor-footwear":
                sizes = (
                    ("S", "M", "L")
                    if "袜" in model.title
                    else ("38", "39", "40", "41", "42", "43", "44")
                )
            if sizes:
                product["options"] = {"size": list(sizes)}
                product["variants"] = [
                    {
                        "product_id": f"{pid}-{size}",
                        "title": f"{model.title}（{size} 码）",
                        "option_values": {"size": size},
                        "price": model.price,
                        "in_stock": not (size == sizes[-1] and index % 4 == 0),
                        "specs": specs
                        | {
                            "尺码": size,
                            "重量说明": "标称样本重量，尺码不同会有差异",
                            "选购限制": model.limitation,
                        },
                    }
                    for size in sizes
                ]
            products.append(product)
    return {
        "store_name": "户外装备助手",
        "currency": "CNY",
        "catalog_version": "outdoor-v1",
        "products": products,
    }


